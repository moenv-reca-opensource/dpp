  const requestedLocale = new URL(window.location.href).searchParams.get('lang')
  const locale = requestedLocale === 'en' ? 'en' : 'zh-TW'
  const localeTag = locale === 'en' ? 'en' : 'zh-Hant-TW'

  const getMessage = (key) => {
    const value = key.split('.').reduce((current, part) => current?.[part], messages[locale])
    return value ?? key.split('.').reduce((current, part) => current?.[part], messages['zh-TW']) ?? key
  }

  const t = (key, values = {}) => {
    const message = String(getMessage(key))
    return message.replace(/\{(\w+)\}/g, (_, name) =>
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`
    )
  }

  const translateAttribute = (node, descriptor) => {
    const [attribute, key] = descriptor.split(':').map((part) => part.trim())
    if (attribute && key) node.setAttribute(attribute, t(key))
  }

  const applyStaticTranslations = () => {
    document.documentElement.lang = localeTag
    document.title = t('pageTitle')
    document.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = t(node.dataset.i18n)
    })
    document.querySelectorAll('[data-i18n-attr]').forEach((node) => {
      node.dataset.i18nAttr.split(',').forEach((descriptor) => translateAttribute(node, descriptor))
    })
    document.querySelectorAll('[data-locale-link]').forEach((link) => {
      const targetLocale = link.dataset.localeLink
      const targetUrl = new URL(window.location.href)
      if (targetLocale === 'en') targetUrl.searchParams.set('lang', 'en')
      else targetUrl.searchParams.delete('lang')
      link.href = targetUrl.href
      link.textContent = targetLocale === 'en' ? t('english') : t('chinese')
      const targetName = targetLocale === 'en' ? t('english') : t('chinese')
      link.setAttribute(
        'aria-label',
        targetLocale === locale ? targetName : t('switchToLanguage', { name: targetName })
      )
      if (targetLocale === locale) {
        link.setAttribute('aria-current', 'page')
        link.removeAttribute('href')
        link.setAttribute('aria-disabled', 'true')
      } else {
        link.removeAttribute('aria-current')
        link.removeAttribute('aria-disabled')
      }
    })
  }

